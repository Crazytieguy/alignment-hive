/// True when shutdown was requested — or the `Supervisor` was dropped
/// (sender gone), which must also stop the loop or it would spin hot.
fn is_shutdown(shutdown_rx: &watch::Receiver<bool>) -> bool {
    shutdown_rx.has_changed().is_err() || *shutdown_rx.borrow()
}

/// Returns true when shutdown was requested during the wait.
async fn wait_or_shutdown(shutdown_rx: &mut watch::Receiver<bool>, wait: Duration) -> bool {
    tokio::select! {
        () = tokio::time::sleep(wait) => is_shutdown(shutdown_rx),
        result = shutdown_rx.changed() => result.is_err() || *shutdown_rx.borrow(),
    }
}

async fn spawn_child(
    binary: &PathBuf,
    paths: &ManagedPaths,
) -> anyhow::Result<tokio::process::Child> {
    let log = tokio::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&paths.log_file)
        .await
        .with_context(|| format!("failed to open {}", paths.log_file.display()))?;
    let mut log_for_stamp = log.try_clone().await?;
    let stamp = format!(
        "\n--- model-router spawning cli-proxy-api at {} ---\n",
        chrono::Utc::now().to_rfc3339()
    );
    let _ = log_for_stamp.write_all(stamp.as_bytes()).await;
    let log_std = log.into_std().await;
    let stderr_log = log_std.try_clone().context("failed to clone log handle")?;

    let mut command = tokio::process::Command::new(binary);
    command
        .arg("-config")
        .arg(&paths.upstream_config)
        .stdin(Stdio::null())
        .stdout(log_std)
        .stderr(stderr_log);
    #[cfg(unix)]
    {
        // New process group so shutdown can kill the child and anything it
        // spawns without touching the router's own group.
        command.process_group(0);
    }
    command.spawn().context("failed to spawn cli-proxy-api")
}

async fn terminate(child: &mut tokio::process::Child, pgid: Option<i32>) {
    #[cfg(unix)]
    if let Some(pgid) = pgid.filter(|pgid| *pgid > 0) {
        // SAFETY: signaling a process group we created.
        unsafe {
            libc::killpg(pgid, libc::SIGTERM);
        }
        if matches!(
            tokio::time::timeout(SHUTDOWN_GRACE, child.wait()).await,
            Ok(Ok(_))
        ) {
            return;
        }
        tracing::warn!("cli-proxy-api ignored SIGTERM; killing");
        // SAFETY: as above.
        unsafe {
            libc::killpg(pgid, libc::SIGKILL);
        }
        let _ = child.wait().await;
        return;
    }
    let _ = child.kill().await;
}

/// Authenticated readiness probe: /v1/models with the injected credential
/// must return 200 JSON. A bare TCP accept is never treated as readiness.
/// Uses the same `GptUpstreamCredential` as the proxy request path so the
/// probe can never validate a different auth shape than real requests use.
async fn probe_ready(
    client: &reqwest::Client,
    base_url: &str,
    credential: &crate::headers::GptUpstreamCredential,
) -> bool {
    let Ok(response) = credential
        .apply(client.get(format!("{base_url}/v1/models")))
        .send()
        .await
    else {
        return false;
    };
    if !response.status().is_success() {
        return false;
    }
    let Ok(body) = response.bytes().await else {
        return false;
    };
    serde_json::from_slice::<serde_json::Value>(&body).is_ok_and(|value| value.is_object())
}

/// True when something is already listening on the loopback port.
async fn port_in_use(port: u16) -> bool {
    tokio::net::TcpStream::connect(("127.0.0.1", port))
        .await
        .is_ok()
}

