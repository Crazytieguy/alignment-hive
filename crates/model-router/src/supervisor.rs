//! Managed-mode supervision of the `CLIProxyAPI` child process.
//!
//! Ownership rules (from the reviewed plan): the child port must be FREE
//! before spawning unless a persisted, identity-verified orphan from this
//! supervisor is still alive; readiness is an authenticated
//! application-level probe, never a bare TCP accept; the exact child PID,
//! start identity, executable, and process group are tracked and killed on
//! shutdown; restarts back off exponentially with a cap and reset after a
//! healthy stretch. Unknown or ambiguous listeners are never adopted or
//! killed.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::Duration;

use anyhow::Context;
use serde::{Deserialize, Serialize};
use tokio::io::AsyncWriteExt;
use tokio::sync::watch;

use crate::config::UpstreamConfig;
use crate::state::{
    Dirs, create_private_dir, import_legacy_auth, load_or_create_secret, write_private_atomic,
};

const SHUTDOWN_GRACE: Duration = Duration::from_secs(5);
const CHILD_IDENTITY_TIMEOUT: Duration = Duration::from_secs(1);
const REAPER_PORT_TIMEOUT: Duration = Duration::from_secs(2);

#[derive(Debug, Deserialize, Serialize)]
struct ChildRecord {
    format_version: u8,
    pid: i32,
    pgid: i32,
    executable: PathBuf,
    /// Platform-native process start identity: `/proc/<pid>/stat` clock ticks
    /// on Linux, and microseconds since the epoch on macOS. `None` marks the
    /// minimal record written immediately after spawn.
    start_time: Option<u64>,
}

#[derive(Debug, Eq, PartialEq)]
struct ProcessIdentity {
    executable: PathBuf,
    start_time: u64,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum ChildRecordStatus {
    Verified,
    Dead,
}

/// Timing knobs, overridable in tests.
#[derive(Clone, Debug)]
pub struct Tuning {
    pub readiness_timeout: Duration,
    pub readiness_poll: Duration,
    pub backoff_initial: Duration,
    pub backoff_max: Duration,
    /// Uptime after which the backoff resets (the child was genuinely healthy).
    pub backoff_reset_uptime: Duration,
}

impl Default for Tuning {
    fn default() -> Self {
        Self {
            readiness_timeout: Duration::from_secs(20),
            readiness_poll: Duration::from_millis(250),
            backoff_initial: Duration::from_secs(1),
            backoff_max: Duration::from_secs(30),
            backoff_reset_uptime: Duration::from_mins(1),
        }
    }
}

/// What the request path needs from managed mode.
#[derive(Clone)]
pub struct ManagedHandle {
    pub base_url: String,
    pub credential: crate::headers::GptUpstreamCredential,
    ready: watch::Receiver<bool>,
}

impl ManagedHandle {
    #[must_use]
    pub fn is_ready(&self) -> bool {
        *self.ready.borrow()
    }
}

/// Owns the supervision task; dropping does NOT kill the child — call
/// [`Supervisor::shutdown`] from the serve teardown path.
pub struct Supervisor {
    handle: ManagedHandle,
    shutdown_tx: watch::Sender<bool>,
    task: tokio::task::JoinHandle<()>,
    /// Live child's process group, shared with the supervision task so
    /// [`Supervisor::shutdown`] can force-kill it if the task does not stop
    /// in time (the pgid cannot be recycled while the child is unreaped).
    child_pgid: SharedPgid,
    child_record_file: PathBuf,
}

type SharedPgid = std::sync::Arc<std::sync::Mutex<Option<i32>>>;

/// Double-quoted YAML scalar encoding for EVERY string interpolated into the
/// generated config. Emits only `\"`, `\\`, and `\uXXXX` escapes — all valid
/// in YAML double-quoted style — and escapes DEL/C1 (which YAML's printable
/// set excludes and go-yaml refuses to scan) in addition to C0. Safety lives
/// here, not in per-field validation.
#[must_use]
pub fn yaml_quote(value: &str) -> String {
    use std::fmt::Write as _;
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{00}'..='\u{1f}' | '\u{7f}'..='\u{9f}' => {
                let _ = write!(out, "\\u{:04x}", character as u32);
            }
            _ => out.push(character),
        }
    }
    out.push('"');
    out
}

/// Renders the `CLIProxyAPI` YAML config the router owns in managed mode.
/// Mirrors the config validated in live experiments: loopback bind, dedicated
/// auth dir, single local api key, cloak/control-panel/telemetry disabled.
/// Keyless providers are omitted (doctor and `verify-providers` flag them).
#[must_use]
#[allow(clippy::missing_panics_doc)] // expect() is on a filtered-to-Some iterator
pub fn upstream_config_yaml(
    port: u16,
    auth_dir: &std::path::Path,
    secret: &str,
    providers: &[crate::config::OpenAiProvider],
) -> String {
    use std::fmt::Write as _;
    let mut yaml = format!(
        r"# Generated by model-router; edits are overwritten on every managed start.
host: {host}
port: {port}

auth-dir: {auth_dir}

api-keys:
  - {secret}

remote-management:
  allow-remote: false
  secret-key: {empty}
  disable-control-panel: true

debug: false
logging-to-file: false
usage-statistics-enabled: false

disable-claude-cloak-mode: true

routing:
  strategy: {strategy}
  session-affinity: false
",
        host = yaml_quote("127.0.0.1"),
        auth_dir = yaml_quote(&auth_dir.display().to_string()),
        secret = yaml_quote(secret),
        empty = yaml_quote(""),
        strategy = yaml_quote("round-robin"),
    );
    let mut keyed = providers
        .iter()
        .filter(|provider| provider.api_key.is_some());
    if keyed.clone().next().is_some() {
        yaml.push_str("\nopenai-compatibility:\n");
        for provider in keyed.by_ref() {
            let api_key = provider.api_key.as_deref().expect("filtered to Some");
            let _ = writeln!(yaml, "  - name: {}", yaml_quote(&provider.name));
            let _ = writeln!(yaml, "    base-url: {}", yaml_quote(&provider.base_url));
            yaml.push_str("    api-key-entries:\n");
            let _ = writeln!(yaml, "      - api-key: {}", yaml_quote(api_key));
            yaml.push_str("    models:\n");
            for model in &provider.models {
                let _ = writeln!(yaml, "      - name: {}", yaml_quote(&model.name));
                let alias = crate::config::derived_alias(&model.routing_id);
                let _ = writeln!(yaml, "        alias: {}", yaml_quote(&alias));
            }
        }
    }
    yaml
}

/// Prepares managed-mode state on disk and returns the paths involved.
/// Idempotent; shared by `serve`, `login`, and `doctor`.
///
/// # Errors
/// Returns an error when directories, the secret, or the config cannot be
/// created.
pub fn prepare_managed_state(
    dirs: &Dirs,
    upstream: &UpstreamConfig,
    providers: &[crate::config::OpenAiProvider],
) -> anyhow::Result<ManagedPaths> {
    create_private_dir(&dirs.state_dir)?;
    create_private_dir(&dirs.auth_dir())?;
    create_private_dir(&dirs.log_dir())?;
    let secret = load_or_create_secret(dirs)?;
    import_legacy_auth(dirs)?;
    let yaml = upstream_config_yaml(upstream.port, &dirs.auth_dir(), &secret, providers);
    write_private_atomic(&dirs.upstream_config_file(), yaml.as_bytes())?;
    Ok(ManagedPaths {
        upstream_config: dirs.upstream_config_file(),
        auth_dir: dirs.auth_dir(),
        log_file: dirs.log_dir().join("cliproxyapi.log"),
        secret,
        port: upstream.port,
    })
}

pub struct ManagedPaths {
    pub upstream_config: PathBuf,
    pub auth_dir: PathBuf,
    pub log_file: PathBuf,
    pub secret: String,
    pub port: u16,
}

impl Supervisor {
    /// Starts the supervision loop. Only cheap local state (secret,
    /// directories) is prepared up front; acquisition, the port-free check,
    /// spawning, and readiness all run — and retry with backoff — INSIDE the
    /// loop, so a failing cliproxy upstream never takes down the Claude gateway.
    ///
    /// # Errors
    /// Returns an error only when local state (directories, the create-once
    /// secret) cannot be prepared.
    pub fn start(
        dirs: &Dirs,
        upstream: &UpstreamConfig,
        providers: Vec<crate::config::OpenAiProvider>,
        tuning: Tuning,
    ) -> anyhow::Result<Self> {
        let secret = {
            create_private_dir(&dirs.state_dir)?;
            load_or_create_secret(dirs)?
        };
        let credential = crate::headers::GptUpstreamCredential::new(&secret)
            .context("generated secret is not a valid header value")?;
        let base_url = format!("http://127.0.0.1:{}", upstream.port);
        let (ready_tx, ready_rx) = watch::channel(false);
        let (shutdown_tx, shutdown_rx) = watch::channel(false);
        let handle = ManagedHandle {
            base_url: base_url.clone(),
            credential: credential.clone(),
            ready: ready_rx,
        };
        let child_pgid: SharedPgid = std::sync::Arc::new(std::sync::Mutex::new(None));
        let task = tokio::spawn(supervise(
            dirs.clone(),
            upstream.clone(),
            providers,
            base_url,
            credential,
            ready_tx,
            shutdown_rx,
            tuning,
            child_pgid.clone(),
        ));
        Ok(Self {
            handle,
            shutdown_tx,
            task,
            child_pgid,
            child_record_file: dirs.upstream_child_file(),
        })
    }

    #[must_use]
    pub fn handle(&self) -> ManagedHandle {
        self.handle.clone()
    }

    /// Stops the supervision loop and terminates the child process group.
    /// Never returns with the child possibly alive: if the task does not
    /// stop within the `SIGTERM` grace plus slack, the tracked group is
    /// `SIGKILL`ed directly.
    pub async fn shutdown(mut self) {
        let _ = self.shutdown_tx.send(true);
        // Child SIGTERM grace plus slack. Every other supervision await is
        // cancellation-aware, keeping this below the service-manager budget.
        let deadline = SHUTDOWN_GRACE + Duration::from_secs(2);
        if tokio::time::timeout(deadline, &mut self.task)
            .await
            .is_err()
        {
            tracing::warn!("supervision task did not stop in time; aborting it");
            // Abort so a detached task can never spawn a child later; every
            // pre-spawn await is cancellation-aware, and there is no await
            // between spawn and pgid tracking, so aborting cannot interleave
            // past a spawn without the slot being set.
            self.task.abort();
            let _ = self.task.await;
            #[cfg(unix)]
            if let Some(pgid) = self
                .child_pgid
                .lock()
                .map_or(None, |slot| *slot)
                .filter(|pgid| *pgid > 0)
            {
                tracing::warn!("force-killing child group");
                // SAFETY: signaling a process group we created; the pgid
                // cannot be recycled while its unreaped leader exists.
                unsafe {
                    libc::killpg(pgid, libc::SIGKILL);
                }
                clear_child_record_path(&self.child_record_file);
            }
        }
    }
}

#[allow(clippy::too_many_arguments)]
async fn supervise(
    dirs: Dirs,
    upstream: UpstreamConfig,
    providers: Vec<crate::config::OpenAiProvider>,
    base_url: String,
    credential: crate::headers::GptUpstreamCredential,
    ready_tx: watch::Sender<bool>,
    mut shutdown_rx: watch::Receiver<bool>,
    tuning: Tuning,
    child_pgid: SharedPgid,
) {
    let probe_client = reqwest::Client::builder()
        .connect_timeout(Duration::from_secs(2))
        .timeout(Duration::from_secs(5))
        .build()
        .expect("probe client always builds");
    let mut backoff = tuning.backoff_initial;
    loop {
        if is_shutdown(&shutdown_rx) {
            return;
        }
        // Every fallible startup step retries here instead of failing the
        // router: acquisition (network), state prep (disk), the port-free
        // check (stale process), spawning, and readiness.
        let attempt = attempt_child(
            &dirs,
            &upstream,
            &providers,
            &base_url,
            &credential,
            &probe_client,
            &ready_tx,
            &mut shutdown_rx,
            &tuning,
            &child_pgid,
        )
        .await;
        let started_at = match attempt {
            ChildAttempt::Shutdown => return,
            ChildAttempt::Failed => None,
            ChildAttempt::Ran { started_at } => Some(started_at),
        };

        if started_at.is_some_and(|started_at| started_at.elapsed() >= tuning.backoff_reset_uptime)
        {
            backoff = tuning.backoff_initial;
        }
        if wait_or_shutdown(&mut shutdown_rx, backoff).await {
            return;
        }
        backoff = (backoff * 2).min(tuning.backoff_max);
    }
}

enum ChildAttempt {
    /// Shutdown was requested; the loop must exit.
    Shutdown,
    /// Setup failed before a child ran; back off and retry.
    Failed,
    /// A child ran (ready or not) and exited or was terminated.
    Ran { started_at: std::time::Instant },
}

#[allow(clippy::too_many_lines, clippy::too_many_arguments)]
async fn attempt_child(
    dirs: &Dirs,
    upstream: &UpstreamConfig,
    providers: &[crate::config::OpenAiProvider],
    base_url: &str,
    credential: &crate::headers::GptUpstreamCredential,
    probe_client: &reqwest::Client,
    ready_tx: &watch::Sender<bool>,
    shutdown_rx: &mut watch::Receiver<bool>,
    tuning: &Tuning,
    child_pgid: &SharedPgid,
) -> ChildAttempt {
    // Acquisition can block on a slow first-run download; stay
    // cancellation-aware so shutdown never waits behind it.
    let binary = tokio::select! {
        acquired = crate::acquire::ensure_upstream(dirs) => match acquired {
            Ok(binary) => binary,
            Err(error) => {
                tracing::error!(%error, "failed to acquire cli-proxy-api; will retry");
                return ChildAttempt::Failed;
            }
        },
        _ = shutdown_rx.changed() => return ChildAttempt::Shutdown,
    };
    let paths = match prepare_managed_state(dirs, upstream, providers) {
        Ok(paths) => paths,
        Err(error) => {
            tracing::error!(%error, "failed to prepare managed state; will retry");
            return ChildAttempt::Failed;
        }
    };
    // The port must be free before every spawn: a foreign listener here
    // would receive prompts and the injected secret. The only exception is a
    // process group whose persisted identity still matches in every field.
    if port_in_use(paths.port).await && !reap_recorded_child(dirs, paths.port).await {
        tracing::error!(
            port = paths.port,
            "port is already in use; refusing to adopt an unknown listener as the cliproxy \
             upstream. If a stale cli-proxy-api is running, stop it, or change \
             [upstreams.cliproxy] port in the config. Will retry."
        );
        return ChildAttempt::Failed;
    }

    // Last line of defense: never spawn after shutdown was requested (the
    // preceding awaits are each cancellation-aware, but re-check anyway).
    if is_shutdown(shutdown_rx) {
        return ChildAttempt::Shutdown;
    }

    let started_at = std::time::Instant::now();
    let mut child = match spawn_child(&binary, &paths).await {
        Ok(child) => child,
        Err(error) => {
            tracing::error!(%error, "failed to spawn cli-proxy-api");
            return ChildAttempt::Failed;
        }
    };
    let pgid = child.id().map(|id| i32::try_from(id).unwrap_or(0));
    let mut record = match persist_minimal_spawned_child(dirs, &binary, &child, pgid) {
        Ok(record) => record,
        Err(error) => {
            tracing::error!(%error, "failed to persist cli-proxy-api child identity");
            discard_unpersistable_child(dirs, child_pgid, &mut child, pgid).await;
            return ChildAttempt::Failed;
        }
    };
    set_pgid(child_pgid, pgid);
    if let Err(error) = enrich_spawned_child_record(dirs, &mut child, &mut record).await {
        tracing::error!(%error, "failed to persist cli-proxy-api child identity");
        discard_unpersistable_child(dirs, child_pgid, &mut child, pgid).await;
        return ChildAttempt::Failed;
    }
    tracing::info!(pid = ?child.id(), "cli-proxy-api started");

    // Readiness: authenticated /v1/models probe against our own child. The
    // probe itself is cancellation-aware — shutdown never waits behind a
    // blackholed probe.
    let ready_deadline = std::time::Instant::now() + tuning.readiness_timeout;
    let mut became_ready = false;
    let mut exited_during_startup = false;
    while std::time::Instant::now() < ready_deadline {
        if is_shutdown(shutdown_rx) {
            terminate(&mut child, pgid).await;
            clear_child_tracking(dirs, child_pgid);
            return ChildAttempt::Shutdown;
        }
        if let Ok(Some(status)) = child.try_wait() {
            tracing::error!(%status, "cli-proxy-api exited during startup");
            clear_child_tracking(dirs, child_pgid);
            exited_during_startup = true;
            break;
        }
        tokio::select! {
            ready = probe_ready(probe_client, base_url, credential) => {
                if ready {
                    became_ready = true;
                    break;
                }
            }
            _ = shutdown_rx.changed() => {
                terminate(&mut child, pgid).await;
                clear_child_tracking(dirs, child_pgid);
                return ChildAttempt::Shutdown;
            }
        }
        if wait_or_shutdown(shutdown_rx, tuning.readiness_poll).await {
            terminate(&mut child, pgid).await;
            clear_child_tracking(dirs, child_pgid);
            return ChildAttempt::Shutdown;
        }
    }
    if exited_during_startup {
        return ChildAttempt::Ran { started_at };
    }
    if became_ready {
        tracing::info!("cliproxy upstream ready");
        let _ = ready_tx.send(true);
    } else {
        // A live child that never becomes ready is a hang, not a crash:
        // terminate it and let the backoff loop start a fresh one, or GPT
        // routing would stay degraded forever.
        tracing::error!(
            log = %paths.log_file.display(),
            "cli-proxy-api did not become ready in time; restarting it (see its log)"
        );
        terminate(&mut child, pgid).await;
        clear_child_tracking(dirs, child_pgid);
        return ChildAttempt::Ran { started_at };
    }

    // Wait for exit or shutdown.
    let attempt = tokio::select! {
        status = child.wait() => {
            let _ = ready_tx.send(false);
            match status {
                Ok(status) => tracing::error!(%status, "cli-proxy-api exited; restarting"),
                Err(error) => tracing::error!(%error, "failed to wait on cli-proxy-api"),
            }
            ChildAttempt::Ran { started_at }
        }
        _ = shutdown_rx.changed() => {
            let _ = ready_tx.send(false);
            terminate(&mut child, pgid).await;
            ChildAttempt::Shutdown
        }
    };
    clear_child_tracking(dirs, child_pgid);
    attempt
}

fn persist_minimal_spawned_child(
    dirs: &Dirs,
    binary: &Path,
    child: &tokio::process::Child,
    pgid: Option<i32>,
) -> anyhow::Result<ChildRecord> {
    let record = minimal_child_record(dirs, binary, child, pgid)?;
    write_child_record(dirs, &record)?;
    Ok(record)
}

async fn enrich_spawned_child_record(
    dirs: &Dirs,
    child: &mut tokio::process::Child,
    record: &mut ChildRecord,
) -> anyhow::Result<()> {
    let deadline = std::time::Instant::now() + CHILD_IDENTITY_TIMEOUT;
    let identity = loop {
        if child.try_wait()?.is_some() {
            anyhow::bail!("cli-proxy-api exited before its identity could be persisted");
        }
        if let Ok(identity) = process_identity(record.pid)
            && identity.executable == record.executable
            && process_group(record.pid).is_ok_and(|live_pgid| live_pgid == record.pgid)
        {
            break identity;
        }
        if std::time::Instant::now() >= deadline {
            anyhow::bail!("cli-proxy-api identity did not become verifiable after spawn");
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    };
    record.start_time = Some(identity.start_time);
    write_child_record(dirs, record)
}

fn minimal_child_record(
    dirs: &Dirs,
    binary: &Path,
    child: &tokio::process::Child,
    pgid: Option<i32>,
) -> anyhow::Result<ChildRecord> {
    let child_pid = child
        .id()
        .and_then(|pid| i32::try_from(pid).ok())
        .filter(|pid| *pid > 0)
        .context("spawned child has no valid PID")?;
    let pgid = pgid
        .filter(|pgid| *pgid == child_pid)
        .context("spawned child is not the leader of the process group model-router created")?;
    Ok(ChildRecord {
        format_version: 1,
        pid: child_pid,
        pgid,
        executable: canonical_cached_executable(&dirs.cache_dir, binary)?,
        start_time: None,
    })
}

fn write_child_record(dirs: &Dirs, record: &ChildRecord) -> anyhow::Result<()> {
    let encoded = serde_json::to_vec_pretty(record).context("failed to encode child identity")?;
    write_private_atomic(&dirs.upstream_child_file(), &encoded)
        .context("failed to write child identity")
}

fn canonical_cached_executable(cache_dir: &Path, executable: &Path) -> anyhow::Result<PathBuf> {
    let executable = fs::canonicalize(executable).with_context(|| {
        format!(
            "failed to resolve cli-proxy-api executable {}",
            executable.display()
        )
    })?;
    let cache_dir = fs::canonicalize(cache_dir)
        .with_context(|| format!("failed to resolve cache dir {}", cache_dir.display()))?;
    anyhow::ensure!(
        executable.starts_with(&cache_dir),
        "cli-proxy-api executable {} is outside model-router cache dir {}",
        executable.display(),
        cache_dir.display()
    );
    Ok(executable)
}

/// Reaps only a process whose PID, process group, executable, and recorded
/// start time all still match a private record written after spawn. A minimal
/// record safely omits only the start-time check. Any ambiguity leaves the
/// listener untouched and preserves the existing refusal path.
async fn reap_recorded_child(dirs: &Dirs, port: u16) -> bool {
    let record = match load_child_record(dirs) {
        Ok(Some(record)) => record,
        Ok(None) => return false,
        Err(error) => {
            tracing::warn!(
                %error,
                "cannot verify recorded cli-proxy-api child; keeping child identity record"
            );
            return false;
        }
    };
    match verify_child_record(dirs, &record) {
        Ok(ChildRecordStatus::Verified) => {}
        Ok(ChildRecordStatus::Dead) => {
            tracing::warn!(
                pid = record.pid,
                "recorded cli-proxy-api PID is dead; clearing child identity record"
            );
            clear_child_record(dirs);
            return false;
        }
        Err(error) => {
            tracing::warn!(
                %error,
                pid = record.pid,
                "recorded child identity does not verify; keeping child identity record"
            );
            return false;
        }
    }

    tracing::warn!(
        pid = record.pid,
        pgid = record.pgid,
        port,
        "reaping identity-verified stale cli-proxy-api process group"
    );
    match verify_child_record(dirs, &record) {
        Ok(ChildRecordStatus::Verified) => {}
        Ok(ChildRecordStatus::Dead) => {
            tracing::warn!(
                pid = record.pid,
                "recorded cli-proxy-api PID died before reaping; clearing child identity record"
            );
            clear_child_record(dirs);
            return false;
        }
        Err(error) => {
            tracing::warn!(
                %error,
                pid = record.pid,
                "recorded child identity changed before reaping; keeping child identity record"
            );
            return false;
        }
    }
    // SIGKILL avoids a later signal after the group leader exits, when the
    // identity could no longer be checked against PID reuse.
    if let Err(error) = kill_stale_process_group(record.pgid) {
        tracing::warn!(
            %error,
            "failed to kill verified stale cli-proxy-api process group"
        );
        return false;
    }
    clear_child_record(dirs);

    let deadline = std::time::Instant::now() + REAPER_PORT_TIMEOUT;
    while port_in_use(port).await {
        if std::time::Instant::now() >= deadline {
            tracing::warn!(port, "port remained occupied after stale-child reaping");
            return false;
        }
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
    true
}

fn load_child_record(dirs: &Dirs) -> anyhow::Result<Option<ChildRecord>> {
    let path = dirs.upstream_child_file();
    let bytes = match fs::read(&path) {
        Ok(bytes) => bytes,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => {
            return Err(error).with_context(|| format!("failed to read {}", path.display()));
        }
    };
    anyhow::ensure!(
        bytes.len() <= 16 * 1024,
        "child identity record is too large"
    );
    serde_json::from_slice(&bytes)
        .with_context(|| format!("failed to parse {}", path.display()))
        .map(Some)
}

fn verify_child_record(dirs: &Dirs, record: &ChildRecord) -> anyhow::Result<ChildRecordStatus> {
    anyhow::ensure!(record.format_version == 1, "unknown child record format");
    anyhow::ensure!(record.pid > 0, "recorded PID is invalid");
    anyhow::ensure!(
        record.pgid == record.pid,
        "recorded process group is invalid"
    );
    if !process_is_live(record.pid).context("failed to check recorded PID liveness")? {
        return Ok(ChildRecordStatus::Dead);
    }
    let executable = canonical_cached_executable(&dirs.cache_dir, &record.executable)?;
    anyhow::ensure!(
        executable == record.executable,
        "recorded executable is not a resolved path under the model-router cache"
    );
    let identity = process_identity(record.pid).context("recorded PID is not inspectable")?;
    anyhow::ensure!(
        identity.executable == record.executable,
        "live executable does not match the record"
    );
    if let Some(start_time) = record.start_time {
        anyhow::ensure!(
            identity.start_time == start_time,
            "live process start time does not match the record"
        );
    }
    anyhow::ensure!(
        process_group(record.pid).is_ok_and(|pgid| pgid == record.pgid),
        "live process group does not match the record"
    );
    Ok(ChildRecordStatus::Verified)
}

fn clear_child_record(dirs: &Dirs) {
    clear_child_record_path(&dirs.upstream_child_file());
}

async fn discard_unpersistable_child(
    dirs: &Dirs,
    child_pgid: &SharedPgid,
    child: &mut tokio::process::Child,
    pgid: Option<i32>,
) {
    // A persistence failure may mean no usable record exists; kill the child
    // rather than risk leaving an unadoptable orphan.
    terminate(child, pgid).await;
    clear_child_tracking(dirs, child_pgid);
}

fn clear_child_tracking(dirs: &Dirs, child_pgid: &SharedPgid) {
    clear_child_record(dirs);
    set_pgid(child_pgid, None);
}

fn clear_child_record_path(path: &Path) {
    if let Err(error) = fs::remove_file(path)
        && error.kind() != std::io::ErrorKind::NotFound
    {
        tracing::warn!(%error, path = %path.display(), "failed to clear child identity record");
    }
}

#[cfg(unix)]
fn process_is_live(pid: i32) -> std::io::Result<bool> {
    // SAFETY: signal 0 only checks whether the supplied PID exists and is
    // signalable; it does not deliver a signal.
    if unsafe { libc::kill(pid, 0) } == 0 {
        return Ok(true);
    }
    let error = std::io::Error::last_os_error();
    match error.raw_os_error() {
        Some(libc::ESRCH) => Ok(false),
        Some(libc::EPERM) => Ok(true),
        _ => Err(error),
    }
}

#[cfg(not(unix))]
fn process_is_live(_pid: i32) -> std::io::Result<bool> {
    Err(std::io::Error::new(
        std::io::ErrorKind::Unsupported,
        "process liveness checks are supported only on Unix",
    ))
}

#[cfg(unix)]
fn process_group(pid: i32) -> std::io::Result<i32> {
    // SAFETY: `getpgid` only inspects the supplied PID.
    let live_group = unsafe { libc::getpgid(pid) };
    if live_group < 0 {
        Err(std::io::Error::last_os_error())
    } else {
        Ok(live_group)
    }
}

#[cfg(not(unix))]
fn process_group(_pid: i32) -> std::io::Result<i32> {
    Err(std::io::Error::new(
        std::io::ErrorKind::Unsupported,
        "process groups are supported only on Unix",
    ))
}

#[cfg(unix)]
fn kill_stale_process_group(pgid: i32) -> std::io::Result<()> {
    // SAFETY: the caller has positively verified the recorded identity and
    // dedicated process group immediately before this call.
    if unsafe { libc::killpg(pgid, libc::SIGKILL) } == 0 {
        Ok(())
    } else {
        Err(std::io::Error::last_os_error())
    }
}

#[cfg(not(unix))]
fn kill_stale_process_group(_pgid: i32) -> std::io::Result<()> {
    Err(std::io::Error::new(
        std::io::ErrorKind::Unsupported,
        "process groups are supported only on Unix",
    ))
}

#[cfg(target_os = "linux")]
fn process_identity(pid: i32) -> std::io::Result<ProcessIdentity> {
    let executable = fs::read_link(format!("/proc/{pid}/exe"))?;
    let stat = fs::read_to_string(format!("/proc/{pid}/stat"))?;
    // The parenthesized comm field may itself contain spaces or `)`, so split
    // after its final closing parenthesis. The remainder starts at field 3;
    // process start time is field 22, hence index 19.
    let fields = stat
        .rsplit_once(") ")
        .map(|(_, fields)| fields)
        .ok_or_else(|| std::io::Error::new(std::io::ErrorKind::InvalidData, "invalid proc stat"))?;
    let start_time = fields
        .split_whitespace()
        .nth(19)
        .ok_or_else(|| std::io::Error::new(std::io::ErrorKind::InvalidData, "missing start time"))?
        .parse()
        .map_err(|error| std::io::Error::new(std::io::ErrorKind::InvalidData, error))?;
    Ok(ProcessIdentity {
        executable,
        start_time,
    })
}

#[cfg(target_os = "macos")]
fn process_identity(pid: i32) -> std::io::Result<ProcessIdentity> {
    use std::ffi::OsStr;
    use std::os::unix::ffi::OsStrExt as _;

    // SAFETY: both calls receive correctly sized, writable buffers; successful
    // byte counts are checked before any fields or path bytes are read.
    unsafe {
        let mut info = std::mem::zeroed::<libc::proc_bsdinfo>();
        let info_size = i32::try_from(std::mem::size_of::<libc::proc_bsdinfo>())
            .expect("proc_bsdinfo size fits i32");
        let read = libc::proc_pidinfo(
            pid,
            libc::PROC_PIDTBSDINFO,
            0,
            std::ptr::addr_of_mut!(info).cast(),
            info_size,
        );
        if read != info_size {
            return Err(std::io::Error::last_os_error());
        }
        let mut path = vec![0_u8; libc::PROC_PIDPATHINFO_MAXSIZE as usize];
        let path_len = libc::proc_pidpath(
            pid,
            path.as_mut_ptr().cast(),
            u32::try_from(path.len()).expect("process path buffer fits u32"),
        );
        if path_len <= 0 {
            return Err(std::io::Error::last_os_error());
        }
        path.truncate(usize::try_from(path_len).expect("positive path length fits usize"));
        let start_time = info
            .pbi_start_tvsec
            .checked_mul(1_000_000)
            .and_then(|seconds| seconds.checked_add(info.pbi_start_tvusec))
            .ok_or_else(|| {
                std::io::Error::new(std::io::ErrorKind::InvalidData, "start time overflow")
            })?;
        Ok(ProcessIdentity {
            executable: PathBuf::from(OsStr::from_bytes(&path)),
            start_time,
        })
    }
}

#[cfg(not(any(target_os = "linux", target_os = "macos")))]
fn process_identity(_pid: i32) -> std::io::Result<ProcessIdentity> {
    Err(std::io::Error::new(
        std::io::ErrorKind::Unsupported,
        "process identity is supported only on macOS and Linux",
    ))
}

