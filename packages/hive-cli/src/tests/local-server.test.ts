interface Reply {
  code: number;
  stdout: string;
  stderr: string;
}
interface Call {
  argv: Array<string>;
  cwd?: string;
  sessionId?: string | null;
}

/** What the one-shot CLI prints, run in-process with the memo off. */
async function oneShot({ argv, cwd = proj, sessionId = null }: Call): Promise<Reply> {
  const env = sessionId === null ? {} : { CLAUDE_CODE_SESSION_ID: sessionId };
  const context = { cwd, env, stdout: [], stderr: [], pause: () => Promise.resolve() };
  const code = await inRequest(context, () => withoutMemo(() => runLocal(localEnv(), argv)));
  return { code, stdout: context.stdout.join(''), stderr: context.stderr.join('') };
}

/** The real CLI's output, spawned. */
async function spawned({ argv, cwd = proj, sessionId = null }: Call): Promise<Reply> {
  const child = Bun.spawn([process.execPath, cli, 'local', ...argv], {
    cwd,
    env: { ...process.env, TZ, CLAUDE_CODE_SESSION_ID: sessionId ?? '', HIVE_LOCAL_CUTOFF: '' },
    stdout: 'pipe',
    stderr: 'pipe',
  });
  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  return { code, stdout, stderr };
}

async function post(socket: string, call: Call, headers: Record<string, string> = {}): Promise<Response> {
  const body = JSON.stringify({ argv: call.argv, cwd: call.cwd ?? proj, sessionId: call.sessionId ?? null });
  return fetch('http://hive/local', { unix: socket, method: 'POST', body, headers });
}

async function served(socket: string, call: Call): Promise<Reply> {
  const response = await post(socket, call);
  expect([call.argv, socket, response.status]).toEqual([call.argv, socket, 200]);
  return (await response.json()) as Reply;
}

