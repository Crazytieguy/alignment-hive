describe('hive local-server', () => {
  let socket = '';
  let log = '';
  let server: ReturnType<typeof startServer>;
  let spawnedSocket = '';

  beforeAll(async () => {
    socket = join(base, 'in.sock');
    log = join(base, 'in.log');
    server = startServer(socket, { log });
    const ensure = Bun.spawn([process.execPath, cli, 'local-server', '--ensure'], {
      cwd: proj,
      env: { ...process.env, TZ, HOME: home, HIVE_LOCAL_CUTOFF: '' },
      stdout: 'pipe',
    });
    spawnedSocket = (JSON.parse(await new Response(ensure.stdout).text()) as { socket: string }).socket;
  });

  afterAll(async () => {
    server.stop('test done');
    await server.stopped;
    // Only the servers this test started: their pids are in its run directory's lock files.
    const run = join(home, '.cache', 'hive', 'run');
    for (const name of existsSync(run) ? execFileSync('ls', [run], { encoding: 'utf8' }).split('\n') : [])
      if (name.endsWith('.lock')) process.kill(Number(readFileSync(join(run, name), 'utf8')), 'SIGTERM');
  });

  /** Every call, through both servers and twice, prints what the one-shot CLI prints. */
  async function same(calls: Array<Call> = CALLS) {
    for (const call of calls) {
      const expected = await oneShot(call);
      for (const at of [socket, spawnedSocket, socket, spawnedSocket])
        expect([call.argv, await served(at, call)]).toEqual([call.argv, expected]);
    }
  }

  test('--ensure starts a server on a private socket under ~/.cache/hive/run', () => {
    expect(spawnedSocket).toMatch(new RegExp(`^${home}/\\.cache/hive/run/local-[0-9a-f]{12}\\.sock$`));
  });

  test('replies are what the one-shot CLI prints, the in-process run matching the spawned CLI', async () => {
    for (const call of CALLS.slice(0, 6)) expect(await oneShot(call)).toEqual(await spawned(call));
    await same();
    // Outlines with and without --replies, in both orders.
    await same([CALLS[4], CALLS[3], CALLS[4]].reverse());
    const repeats = readFileSync(log, 'utf8')
      .trim()
      .split('\n')
      .map((l) => JSON.parse(l) as { verb?: string; hits?: number; misses?: number })
      .filter((l) => l.verb === 'outline');
    expect(repeats.at(-1)).toMatchObject({ misses: 0 });
  });

  const mutations: Array<[string, () => Promise<void> | void]> = [
    ['a complete append', () => appendFile(join(projDir, `${B}.jsonl`), line(rec('user', 'Shorter.', { cwd: proj })))],
    [
      'a partial line, then its completion',
      () =>
        appendFile(join(projDir, `${B}.jsonl`), line(rec('assistant', [{ type: 'text', text: 'sn' }])).slice(0, 30)),
    ],
    [
      'the partial line completed',
      async () => {
        const path = join(projDir, `${B}.jsonl`);
        const text = await readFile(path, 'utf8');
        const cut = text.lastIndexOf('\n') + 1;
        await writeFile(path, text.slice(0, cut) + line(rec('assistant', [{ type: 'text', text: 'sn' }])));
      },
    ],
    [
      'a late tool_result that takes no entry number',
      () =>
        appendFile(
          join(projDir, `${A}.jsonl`),
          line(rec('user', [{ type: 'tool_result', tool_use_id: 'tu-ask', content: 'User answered: yes' }])),
        ),
    ],
    [
      'a rewind and a compaction',
      async () => {
        const path = join(projDir, `${A}.jsonl`);
        await appendFile(path, line({ ...rec('user', 'Instead, try this.'), parentUuid: 'u-1' }));
        await appendFile(path, line(rec('system', undefined, { subtype: 'compact_boundary', content: 'Compacted' })));
      },
    ],
    [
      'a bookkeeping append to an old file',
      () => appendFile(join(root, '-elsewhere', `${C}.jsonl`), line({ type: 'queue-operation', operation: 'x' })),
    ],
    [
      'a same-size rewrite in place',
      async () => {
        const path = join(projDir, `${B}.jsonl`);
        await writeFile(path, (await readFile(path, 'utf8')).replace('Name the script.', 'Name the scrypt.'));
      },
    ],
    [
      'an ExitWorktree move',
      async () => {
        await mkdir(join(root, '-moved'), { recursive: true });
        await rename(join(projDir, `${B}.jsonl`), join(root, '-moved', `${B}.jsonl`));
      },
    ],
    ['a deleted session', () => rm(join(root, '-moved', `${B}.jsonl`))],
    [
      'a new session sharing the first 8 characters',
      () =>
        write(join(projDir, `${a8}-1111-4000-8000-000000000009.jsonl`), lines([rec('user', 'Twin.', { cwd: proj })])),
    ],
    [
      'git worktree add, with a session there',
      async () => {
        git(['worktree', 'add', '-q', join(base, 'wt')]);
        const wtDir = join(root, toClaudeProjectDirName(join(base, 'wt')));
        await write(
          join(wtDir, 'dd000004-0000-4000-8000-000000000004.jsonl'),
          lines([rec('user', 'In the worktree.', { cwd: join(base, 'wt') })]),
        );
      },
    ],
    ['git worktree remove', () => void git(['worktree', 'remove', '--force', join(base, 'wt')])],
    [
      'a registry edit',
      () => write(join(proj, '.claude', 'hive', 'transcripts-dirs'), `${join(root, '-elsewhere')}\n`),
    ],
  ];

  for (const [name, mutate] of mutations)
    test(`after ${name}, replies are still what the one-shot CLI prints`, async () => {
      await mutate();
      await same();
    });

  test('a changed session id reads another `current`', async () => {
    await same([
      { argv: ['outline', 'current', '--no-agents'], sessionId: B },
      { argv: ['outline', 'current', '--no-agents'], sessionId: A },
      { argv: ['outline', 'current', '--no-agents'], sessionId: null },
    ]);
  });

  test('a warm request is answered like any other, and one like it running or just answered is not run again', async () => {
    const call = { argv: ['outline', A, '--replies', '--no-agents', '--clip', '0'] };
    const expected = await oneShot(call);
    const warm = async () => (await post(socket, call, { 'x-hive-warm': '1' })).json();
    const before = readFileSync(log, 'utf8').split('\n').length;
    expect(await Promise.all([warm(), warm()])).toEqual([expected, expected]);
    expect(await warm()).toEqual(expected);
    const added = readFileSync(log, 'utf8')
      .trim()
      .split('\n')
      .slice(before - 1);
    expect(added.filter((l) => l.includes('"lane":"warm"'))).toHaveLength(1);
  });

  test('other verbs and malformed calls are refused', async () => {
    for (const body of [
      { argv: ['show', a8], cwd: proj, sessionId: null },
      { argv: ['grep', 'x'], cwd: proj, sessionId: null },
      { argv: [], cwd: proj, sessionId: null },
      { argv: ['sessions'], cwd: 'relative', sessionId: null },
      { argv: ['sessions'], cwd: proj, sessionId: 7 },
    ]) {
      const response = await fetch('http://hive/local', { unix: socket, method: 'POST', body: JSON.stringify(body) });
      expect(response.status).toBe(400);
    }
    const response = await fetch('http://hive/local', { unix: socket, method: 'POST', body: '{' });
    expect(response.status).toBe(400);
    expect((await fetch('http://hive/ping', { unix: socket })).status).toBe(200);
  });
});

describe('hive local-server --ensure', () => {
  const ensure = async (env: Record<string, string>, cwd = proj) => {
    const child = Bun.spawn([process.execPath, cli, 'local-server', '--ensure'], {
      cwd,
      env: { ...process.env, TZ, HIVE_LOCAL_CUTOFF: '', ...env },
      stdout: 'pipe',
    });
    const [stdout, code] = await Promise.all([new Response(child.stdout).text(), child.exited]);
    expect(code).toBe(0);
    return JSON.parse(stdout) as { socket?: string };
  };
  const stopAll = (ensureHome: string) => {
    const run = join(ensureHome, '.cache', 'hive', 'run');
    if (!existsSync(run)) return;
    for (const name of execFileSync('ls', [run], { encoding: 'utf8' }).split('\n'))
      if (name.endsWith('.lock')) process.kill(Number(readFileSync(join(run, name), 'utf8')), 'SIGTERM');
  };

  test('concurrent ensures start one server; a cutoff, another zone or git config and a long path get none or their own', async () => {
    const ensureHome = await shortTemp('hle-');
    try {
      const sockets = await Promise.all([1, 2, 3].map(() => ensure({ HOME: ensureHome })));
      expect(new Set(sockets.map((s) => s.socket)).size).toBe(1);
      const socket = sockets[0].socket!;
      const logText = readFileSync(socket.replace(/\.sock$/, '.log'), 'utf8');
      expect(logText.split('\n').filter((l) => l.includes('"start"'))).toHaveLength(1);
      expect(await ensure({ HOME: ensureHome, HIVE_LOCAL_CUTOFF: '2026-09-20T00:00:00Z' })).toEqual({});
      const zone = TZ === 'Asia/Tokyo' ? 'Europe/Paris' : 'Asia/Tokyo';
      const other = await ensure({ HOME: ensureHome, TZ: zone });
      expect(other.socket).toBeString();
      expect(other.socket).not.toBe(socket);
      // git reads its global config there.
      const xdg = await ensure({ HOME: ensureHome, XDG_CONFIG_HOME: join(ensureHome, 'xdg') });
      expect(xdg.socket).toBeString();
      expect([socket, other.socket]).not.toContain(xdg.socket);
      expect(await ensure({ HOME: join(ensureHome, 'x'.repeat(80)) })).toEqual({});
    } finally {
      stopAll(ensureHome);
      await rm(ensureHome, { recursive: true, force: true });
    }
  });

  test('a stale socket and a dead lock holder are taken over', async () => {
    const ensureHome = await shortTemp('hle-');
    try {
      const first = (await ensure({ HOME: ensureHome })).socket!;
      stopAll(ensureHome);
      for (let i = 0; i < 100 && existsSync(first.replace(/\.sock$/, '.lock')); i++) await Bun.sleep(20);
      // The socket stays behind with nothing listening on it; a lock names a pid that is gone.
      expect(existsSync(first)).toBe(true);
      writeSync(first.replace(/\.sock$/, '.lock'), '999999');
      const again = await ensure({ HOME: ensureHome });
      expect(again.socket).toBe(first);
      expect((await fetch('http://hive/ping', { unix: first })).status).toBe(200);
    } finally {
      stopAll(ensureHome);
      await rm(ensureHome, { recursive: true, force: true });
    }
  });
});

describe('lanes', () => {
  test('a prompt-time request goes before waiting warm ones, and takes over a running warm one at its pause', async () => {
    const queue = lanes();
    const order: Array<string> = [];
    const job = async (name: string, lane: Lane, pauses = 0) => {
      await queue.take(lane);
      try {
        order.push(`${name} start`);
        for (let i = 0; i < pauses; i++) await queue.pause(lane);
        order.push(`${name} end`);
      } finally {
        queue.give();
      }
    };
    const warm = job('warm', 'warm', 3);
    const second = job('second warm', 'warm');
    const prompt = job('prompt', 'prompt');
    await Promise.all([warm, second, prompt]);
    expect(order).toEqual([
      'warm start',
      'prompt start',
      'prompt end',
      'warm end',
      'second warm start',
      'second warm end',
    ]);
    expect(queue.busy()).toBe(false);
  });

  test("a warm request's pauses let a reply under way reach its reader", async () => {
    const socket = join(base, 'drain.sock');
    const server = Bun.serve({ unix: socket, fetch: () => new Response('x'.repeat(2 ** 20)) });
    const queue = lanes();
    let warmEnded = 0;
    const warm = (async () => {
      await queue.take('warm');
      for (const until = performance.now() + 1500; performance.now() < until;) {
        for (const slice = performance.now() + 20; performance.now() < slice;) {
          // a stretch of files read
        }
        await queue.pause('warm');
      }
      warmEnded = performance.now();
      queue.give();
    })();
    try {
      await Bun.sleep(30);
      const read = await fetch('http://hive/', { unix: socket }).then((r) => r.text());
      expect(read.length).toBe(2 ** 20);
      expect(warmEnded).toBe(0);
    } finally {
      await warm;
      await server.stop(true);
    }
  });
});

describe('server lifetime', () => {
  test('a changed executable answers 409 and stops the server', async () => {
    const socket = join(base, 'exe.sock');
    let identity = 'one';
    const server = startServer(socket, { identity: () => identity });
    expect((await post(socket, { argv: ['sessions', '-n', '1'] })).status).toBe(200);
    identity = 'two';
    expect((await post(socket, { argv: ['sessions', '-n', '1'] })).status).toBe(409);
    expect(await server.stopped).toBe('executable changed');
    expect(existsSync(socket)).toBe(false);
  });

  test('it stops when idle, and when its socket is removed', async () => {
    const idle = startServer(join(base, 'idle.sock'), { idleMs: 30, tickMs: 20 });
    expect(await idle.stopped).toBe('idle');
    const socket = join(base, 'gone.sock');
    const gone = startServer(socket, { tickMs: 20 });
    await rm(socket);
    expect(await gone.stopped).toBe('socket replaced');
  });
});
